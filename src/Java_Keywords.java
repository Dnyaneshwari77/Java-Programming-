/*

Definition:- In Java, Keywords are the Reserved words in a programming language that are used for some internal process or represent some predefined actions. These words are therefore not allowed to use as variable names or objects.
 */
public class Java_Keywords {
    public static void main(String[] args) {

        // Using final and int keyword
        final int x = 10;

        // Using if and else keywords
        if(x>10){
            System.out.println("Failed");
        }
        else{
            System.out.println("Succesful Demonstration"
                    +" of keywords");
        }

    }
}
